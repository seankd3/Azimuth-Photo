import {
    createDateScrubberController,
    dateGroupOffset as dateGroupOffsetCore,
    findDateGroupHeader as findDateGroupHeaderCore,
    isDateSortValue,
    jumpToDateGroup as jumpToDateGroupCore,
    renderDateScrubber as renderDateScrubberCore,
    setActiveDateScrubberGroup as setActiveDateScrubberGroupCore,
    setupDateScrubberScrollTracking as setupDateScrubberScrollTrackingCore,
    syncDateScrubberVisibility as syncDateScrubberVisibilityCore,
    teardownDateScrubberScrollTracking as teardownDateScrubberScrollTrackingCore,
} from '../library/date_scrubber.js';

export function createLegacyDateScrubberBridge({
    documentImpl = document,
    windowImpl = window,
    fetchImpl = fetch,
    createDateScrubberControllerImpl = createDateScrubberController,
    dateGroupOffsetImpl = dateGroupOffsetCore,
    findDateGroupHeaderImpl = findDateGroupHeaderCore,
    isDateSortValueImpl = isDateSortValue,
    jumpToDateGroupImpl = jumpToDateGroupCore,
    renderDateScrubberImpl = renderDateScrubberCore,
    setActiveDateScrubberGroupImpl = setActiveDateScrubberGroupCore,
    setupDateScrubberScrollTrackingImpl = setupDateScrubberScrollTrackingCore,
    syncDateScrubberVisibilityImpl = syncDateScrubberVisibilityCore,
    teardownDateScrubberScrollTrackingImpl = teardownDateScrubberScrollTrackingCore,
    currentLibraryView = () => 'grid',
    currentSearchMode = () => 'library',
    currentQueryString = () => '',
    getRankingsSort = () => '',
    getDateGroups = () => [],
    setDateGroups = () => {},
    nextDateScrubberGeneration = () => 0,
    isCurrentDateScrubberGeneration = () => true,
    libraryScrollRoot = () => null,
    scrollLibraryContainerToElement = () => {},
    resetForDateOffset = () => 0,
    isCurrentDateJump = () => true,
    loadRankings = async () => {},
} = {}) {
    let controller = null;
    const bridge = {
        isDateSortActive: () => isDateSortValueImpl(getRankingsSort()),
        isDateScrubberActive: () => bridge.isDateSortActive() && currentSearchMode() === 'library',
        syncDateScrubberVisibility: () => syncDateScrubberVisibilityImpl({
            documentImpl,
            currentLibraryView,
            isDateScrubberActive: bridge.isDateScrubberActive,
        }),
        findDateGroupHeader: (group) => findDateGroupHeaderImpl(group, documentImpl),
        dateGroupOffset: (group) => dateGroupOffsetImpl(getDateGroups(), group),
        setActiveDateScrubberGroup: (group) => setActiveDateScrubberGroupImpl(group, documentImpl),
        teardownDateScrubberScrollTracking: () => teardownDateScrubberScrollTrackingImpl(),
        setupDateScrubberScrollTracking: () => setupDateScrubberScrollTrackingImpl({
            scrollRoot: libraryScrollRoot(),
            documentImpl,
        }),
        jumpToDateGroup: async (group) => jumpToDateGroupImpl(group, {
            isActive: bridge.isDateScrubberActive,
            findHeader: bridge.findDateGroupHeader,
            setActiveGroup: bridge.setActiveDateScrubberGroup,
            scrollToElement: scrollLibraryContainerToElement,
            getOffset: bridge.dateGroupOffset,
            resetForOffset: resetForDateOffset,
            isCurrentJump: isCurrentDateJump,
            loadRankings,
            scrollRoot: libraryScrollRoot,
            documentImpl,
        }),
        updateDateScrubber: () => controller.updateDateScrubber(),
        renderDateScrubber: () => controller.renderDateScrubber(),
        setupScrubberScrollObserver: () => controller.setupScrubberScrollObserver(),
    };

    controller = createDateScrubberControllerImpl({
        documentImpl,
        windowImpl,
        fetchImpl,
        isActive: bridge.isDateScrubberActive,
        getQueryString: currentQueryString,
        getSortValue: getRankingsSort,
        getGroups: getDateGroups,
        setGroups: setDateGroups,
        nextGeneration: nextDateScrubberGeneration,
        isCurrentGeneration: isCurrentDateScrubberGeneration,
        onJump: bridge.jumpToDateGroup,
        setupScrollObserver: bridge.setupDateScrubberScrollTracking,
        syncVisibility: bridge.syncDateScrubberVisibility,
        teardownScrollTracking: bridge.teardownDateScrubberScrollTracking,
        renderDateScrubberImpl,
    });

    return bridge;
}
