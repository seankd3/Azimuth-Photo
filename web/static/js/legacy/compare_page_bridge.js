import { createComparePageController } from '../compare/page_controller.js';

export function createLegacyComparePageBridge({
    documentImpl,
    windowImpl,
    setTimeoutImpl,
    getMosaicSize,
    initBottomBarMeasurement,
    startAIStatusPolling,
    handleCompareKey,
    scheduleMosaicRender,
    submitComparison,
    restoreFilters,
    restoreSearchState,
    initSearchInputControls,
    setCompareMode,
    setMosaicStrategy,
    mosaicShuffle,
    loadFolderList,
    scheduleFilterOptionsLoad,
    initStarHover,
    clearSearch,
    setFilter,
    toggleMetadataFilters,
    toggleFilter,
    toggleStar,
    setThumbSize,
    toggleBackgroundWorkPanel,
    createComparePageControllerImpl = createComparePageController,
} = {}) {
    const controller = createComparePageControllerImpl({
        documentImpl,
        windowImpl,
        setTimeoutImpl,
        getMosaicSize,
        initBottomBarMeasurement,
        startAIStatusPolling,
        handleCompareKey,
        scheduleMosaicRender,
        submitComparison,
        restoreFilters,
        restoreSearchState,
        initSearchInputControls,
        setCompareMode,
        setMosaicStrategy,
        mosaicShuffle,
        loadFolderList,
        scheduleFilterOptionsLoad,
        initStarHover,
        clearSearch,
        setFilter,
        toggleMetadataFilters,
        toggleFilter,
        toggleStar,
        setThumbSize,
        toggleBackgroundWorkPanel,
    });

    return {
        initCompare: (...args) => controller.initCompare(...args),
    };
}
